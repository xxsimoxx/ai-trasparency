<?php

defined( 'ABSPATH' ) || exit;

/**
 * Handles frontend AI content rendering.
 */
class AI_Frontend {

	/**
	 * Media component.
	 *
	 * @var AI_Media
	 */
	private $media;

	/**
	 * Constructor.
	 *
	 * @param AI_Media $media Media component.
	 */
	public function __construct( AI_Media $media ) {

		$this->media = $media;
	}

	/**
	 * Register frontend hooks.
	 *
	 * @return void
	 */
	public function register_hooks() {

		/*
		 * Images generated through wp_get_attachment_image().
		 */
		add_filter(
			'wp_get_attachment_image',
			[ $this, 'filter_attachment_image' ],
			10,
			5
		);

		/*
		 * Images found in post/page content.
		 */
		add_filter(
			'wp_content_img_tag',
			[ $this, 'filter_content_image' ],
			10,
			3
		);

		/*
		 * Featured images.
		 */
		add_filter(
			'post_thumbnail_html',
			[ $this, 'filter_post_thumbnail' ],
			10,
			5
		);

		/*
		 * Complete post content.
		 *
		 * Disabled by default. Processing can be enabled through
		 * the ai_transparency_process_content filter.
		 */
		add_filter(
			'the_content',
			[ $this, 'filter_content' ],
			20
		);

		/*
		 * Register the stylesheet.
		 */
		add_action(
			'wp_enqueue_scripts',
			[ $this, 'enqueue_assets' ]
		);
	}

	/**
	 * Filter images generated by wp_get_attachment_image().
	 *
	 * @param string       $html          Image HTML.
	 * @param int          $attachment_id Attachment ID.
	 * @param string|array $size          Image size.
	 * @param bool         $icon          Whether the image is an icon.
	 * @param array        $attr          Image attributes.
	 * @return string
	 */
	public function filter_attachment_image(
		$html,
		$attachment_id,
		$size,
		$icon,
		$attr
	) {

		return $this->wrap_image(
			$html,
			$attachment_id
		);
	}

	/**
	 * Filter images found in post/page content.
	 *
	 * WordPress normally adds a class such as:
	 *
	 * wp-image-123
	 *
	 * to images inserted through the Media Library.
	 *
	 * @param string $image         Image HTML.
	 * @param string $context       Current post content.
	 * @param int    $attachment_id Attachment ID, when available.
	 * @return string
	 */
	public function filter_content_image(
		$image,
		$context,
		$attachment_id
	) {

		/*
		 * Some WordPress/ClassicPress versions may not provide
		 * the attachment ID to this filter. In that case, try
		 * to extract it from the wp-image-N class.
		 */
		if ( ! $attachment_id ) {

			if (
				preg_match(
					'/\bwp-image-(\d+)\b/',
					$image,
					$matches
				)
			) {
				$attachment_id = absint(
					$matches[1]
				);
			}
		}

		if ( ! $attachment_id ) {
			return $image;
		}

		return $this->wrap_image(
			$image,
			$attachment_id
		);
	}

	/**
	 * Filter featured image HTML.
	 *
	 * @param string       $html              Featured image HTML.
	 * @param int          $post_id           Post ID.
	 * @param int          $post_thumbnail_id Featured image ID.
	 * @param string|array $size              Image size.
	 * @param array        $attr              Image attributes.
	 * @return string
	 */
	public function filter_post_thumbnail(
		$html,
		$post_id,
		$post_thumbnail_id,
		$size,
		$attr
	) {

		if ( ! $post_thumbnail_id ) {
			return $html;
		}

		return $this->wrap_image(
			$html,
			$post_thumbnail_id
		);
	}

	/**
	 * Filter complete post content.
	 *
	 * This is disabled by default and can be enabled through
	 * the ai_transparency_process_content filter.
	 *
	 * @param string $content Post content.
	 * @return string
	 */
	public function filter_content( $content ) {

		if ( ! $this->should_process_content() ) {
			return $content;
		}

		return $this->process_content_images(
			$content
		);
	}

	/**
	 * Determine whether complete post content should be processed.
	 *
	 * @return bool
	 */
	private function should_process_content() {

		return (bool) apply_filters(
			'ai_transparency_process_content',
			false
		);
	}

	/**
	 * Determine whether content images should be matched by URL.
	 *
	 * @return bool
	 */
	private function should_match_content_images_by_url() {

		return (bool) apply_filters(
			'ai_transparency_match_content_images_by_url',
			false
		);
	}

	/**
	 * Process images found in post content.
	 *
	 * @param string $content Post content.
	 * @return string
	 */
	private function process_content_images( $content ) {

		return preg_replace_callback(
			'/<img\b[^>]*>/i',
			function ( $matches ) {

				$image = $matches[0];

				/*
				 * First try to identify the attachment using
				 * the standard WordPress wp-image-N class.
				 */
				if (
					preg_match(
						'/\bwp-image-(\d+)\b/',
						$image,
						$id_matches
					)
				) {
					$attachment_id = absint(
						$id_matches[1]
					);

					return $this->wrap_image(
						$image,
						$attachment_id
					);
				}

				/*
				 * If enabled, try to identify the attachment
				 * using the image URL.
				 */
				if (
					$this->should_match_content_images_by_url()
				) {
					$attachment_id = $this->get_attachment_id_by_image_url(
						$image
					);

					if ( $attachment_id ) {
						return $this->wrap_image(
							$image,
							$attachment_id
						);
					}
				}

				return $image;
			},
			$content
		);
	}

	/**
	 * Find an attachment ID from an image URL.
	 *
	 * @param string $image Image HTML.
	 * @return int
	 */
	private function get_attachment_id_by_image_url( $image ) {

		if (
			! preg_match(
				'/\bsrc\s*=\s*["\']([^"\']+)["\']/i',
				$image,
				$matches
			)
		) {
			return 0;
		}

		$url = html_entity_decode(
			$matches[1],
			ENT_QUOTES,
			'UTF-8'
		);

		$url = esc_url_raw( $url );

		if ( ! $url ) {
			return 0;
		}

		/*
		 * Remove WordPress image size suffixes.
		 */
		$url = $this->remove_image_size_suffix(
			$url
		);

		/*
		 * First use WordPress's native lookup.
		 */
		$attachment_id = attachment_url_to_postid(
			$url
		);

		if ( $attachment_id ) {
			return absint( $attachment_id );
		}

		/*
		 * Fallback: compare the relative upload path against
		 * the _wp_attached_file metadata.
		 */
		$uploads = wp_upload_dir();

		if (
			empty( $uploads['baseurl'] ) ||
			empty( $uploads['basedir'] )
		) {
			return 0;
		}

		$baseurl = trailingslashit(
			$uploads['baseurl']
		);

		if (
			0 !== strpos(
				$url,
				$baseurl
			)
		) {
			return 0;
		}

		$relative_path = ltrim(
			substr(
				$url,
				strlen( $baseurl )
			),
			'/'
		);

		if ( ! $relative_path ) {
			return 0;
		}

		global $wpdb;

		$attachment_id = $wpdb->get_var(
			$wpdb->prepare(
				"
				SELECT post_id
				FROM {$wpdb->postmeta}
				WHERE meta_key = '_wp_attached_file'
				AND meta_value = %s
				LIMIT 1
				",
				$relative_path
			)
		);

		return absint(
			$attachment_id
		);
	}

	/**
	 * Remove a WordPress image size suffix from a URL.
	 *
	 * @param string $url Image URL.
	 * @return string
	 */
	private function remove_image_size_suffix( $url ) {

		$path = wp_parse_url(
			$url,
			PHP_URL_PATH
		);

		if ( ! $path ) {
			return $url;
		}

		$extension = pathinfo(
			$path,
			PATHINFO_EXTENSION
		);

		if ( ! $extension ) {
			return $url;
		}

		$basename = pathinfo(
			$path,
			PATHINFO_FILENAME
		);

		/*
		 * Match standard WordPress size suffixes such as:
		 *
		 * -300x200
		 * -768x512
		 * -1536x1024
		 */
		$basename = preg_replace(
			'/-(\d+)x(\d+)$/',
			'',
			$basename
		);

		$directory = dirname(
			$path
		);

		$directory = (
			'.' === $directory
				? ''
				: trailingslashit( $directory )
		);

		$clean_path = $directory
			. $basename
			. '.'
			. $extension;

		$scheme = wp_parse_url(
			$url,
			PHP_URL_SCHEME
		);

		$host = wp_parse_url(
			$url,
			PHP_URL_HOST
		);

		if ( $scheme && $host ) {
			$clean_url = $scheme . '://' . $host . $clean_path;
		} else {
			$clean_url = $clean_path;
		}

		return $clean_url;
	}

	/**
	 * Wrap an image when disclosure is required.
	 *
	 * @param string $html          Image HTML.
	 * @param int    $attachment_id Attachment ID.
	 * @return string
	 */
	private function wrap_image(
		$html,
		$attachment_id
	) {

		$attachment_id = absint(
			$attachment_id
		);

		if ( ! $attachment_id ) {
			return $html;
		}

		$type = $this->media->get_type(
			$attachment_id
		);

		/*
		 * The image has no AI classification.
		 */
		if ( ! $type ) {
			return $html;
		}

		/*
		 * The image has an AI classification but
		 * disclosure is not currently required.
		 */
		if (
			! $this->media->should_disclose(
				$attachment_id
			)
		) {
			return $html;
		}

		$label = $this->media->get_label(
			$type
		);

		if ( ! $label ) {
			return $html;
		}

		$class = sprintf(
			'ai-content ai-logo ai-%s',
			$type
		);

		/*
		 * Avoid accidentally wrapping an image twice.
		 */
		if (
			strpos(
				$html,
				'ai-content'
			) !== false
		) {
			return $html;
		}

		return sprintf(
			'<span class="%1$s"><span class="screen-reader-text">%2$s</span>%3$s</span>',
			esc_attr( $class ),
			esc_html( $label ),
			$html
		);
	}

	/**
	 * Enqueue frontend stylesheet.
	 *
	 * @return void
	 */
	public function enqueue_assets() {

		wp_enqueue_style(
			'ai-transparency',
			AI_TRANSPARENCY_URL . 'assets/css/ai-transparency.css',
			[],
			AI_TRANSPARENCY_VERSION
		);
	}
}
